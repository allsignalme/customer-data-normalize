// Generates the Meta lookup tables for Go and TypeScript from data/meta-tables.json.
// Usage: node scripts/gen-tables.mjs   (then gofmt -w meta/tables_gen.go)
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;
const t = JSON.parse(readFileSync(`${root}data/meta-tables.json`, "utf8"));
// STATE order follows the reference: Canadian provinces first, then US states (first contained name wins).
const states = [...t.ca_provinces, ...t.us_states];
const header = `Code generated by scripts/gen-tables.mjs from data/meta-tables.json. DO NOT EDIT.`;
const q = (s) => JSON.stringify(s);

const goPairs = (name, pairs) =>
  `var ${name} = []nameCode{\n${pairs.map(([k, v]) => `\t{${q(k)}, ${q(v)}},`).join("\n")}\n}\n`;
const goWords = (name, words) => `var ${name} = []string{\n${words.map((w) => `\t${q(w)},`).join("\n")}\n}\n`;
writeFileSync(
  `${root}meta/tables_gen.go`,
  `// ${header}\n// Source: ${t.source}\n\npackage meta\n\n` +
    goPairs("stateNames", states) + "\n" + goPairs("countryNames", t.countries) + "\n" +
    goWords("maleWords", t.gender_male) + "\n" + goWords("femaleWords", t.gender_female),
);

const tsPairs = (name, pairs) =>
  `export const ${name}: ReadonlyArray<readonly [string, string]> = [\n${pairs.map(([k, v]) => `  [${q(k)}, ${q(v)}],`).join("\n")}\n];\n`;
const tsWords = (name, words) => `export const ${name}: ReadonlyArray<string> = [\n${words.map((w) => `  ${q(w)},`).join("\n")}\n];\n`;
writeFileSync(
  `${root}src/meta-tables.gen.ts`,
  `// ${header}\n// Source: ${t.source}\n\n` +
    tsPairs("STATE_NAMES", states) + "\n" + tsPairs("COUNTRY_NAMES", t.countries) + "\n" +
    tsWords("MALE_WORDS", t.gender_male) + "\n" + tsWords("FEMALE_WORDS", t.gender_female),
);
